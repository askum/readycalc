import { readdir, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { visibility } from './search-visibility.mjs';
import { loadMagazineArticles } from './magazine-data.mjs';

const root = resolve(import.meta.dirname, '..');
const publicPaths = new Set(['/','/index.html','/robots.txt','/sitemap.xml','/ads.txt','/404.html','/404']);
for (const entry of await readdir(root, { withFileTypes: true })) {
  if (entry.isFile() && /^naver[a-z0-9]+(?:\.html)?$/i.test(entry.name)) publicPaths.add(`/${entry.name}`);
}
for (const slug of ['about','privacy','terms','contact','methodology','disclaimer','magazine']) {
  publicPaths.add(`/${slug}`); publicPaths.add(`/${slug}/`); publicPaths.add(`/${slug}/index.html`);
}
for (const article of await loadMagazineArticles()) {
  const route = `/magazine/${article.slug}`;
  publicPaths.add(route); publicPaths.add(`${route}/`); publicPaths.add(`${route}/index.html`);
}
for (const slug of visibility.indexable) {
  for (const prefix of ['', '/calculator']) {
    const route = `${prefix}/${slug}`;
    publicPaths.add(route); publicPaths.add(`${route}/`); publicPaths.add(`${route}/index.html`);
  }
}
const paths = [...publicPaths].sort().map((path) => `  ${JSON.stringify(path)},`).join('\n');
const source = `// Generated by scripts/sync-public-worker.mjs. Only curated pages are published.\nconst publicPaths = new Set([\n${paths}\n]);\nconst missingPage = '<!doctype html><html lang="ko"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="robots" content="noindex"><title>페이지를 찾을 수 없습니다 | 생활계산소</title><h1>페이지를 찾을 수 없습니다.</h1><p>현재 제공하지 않는 페이지입니다.</p><a href="/">생활계산소 홈으로</a></html>';\nexport default {\n  async fetch(request, env) {\n    const url = new URL(request.url);\n    const asset = /^\\/assets\\/[a-zA-Z0-9_/-]+\\.(?:js|css|png|jpg|jpeg|svg|webp|ico|woff2?)$/.test(url.pathname) && !url.pathname.includes('..');\n    if (publicPaths.has(url.pathname) || asset) return env.ASSETS.fetch(request);\n    return new Response(request.method === 'HEAD' ? null : missingPage, {\n      status: 404,\n      headers: { 'Content-Type':'text/html; charset=utf-8', 'X-Robots-Tag':'noindex', 'Cache-Control':'no-store', 'X-Content-Type-Options':'nosniff' }\n    });\n  }\n};\n`;
await writeFile(resolve(root, '_worker.js'), source);
console.log(`Worker allowlist: ${publicPaths.size} public paths.`);
