export default {
  async fetch(request, env) {
    const url = new URL(request.url);
    // Compare exact paths. Encoded and alternate spellings are denied, not forwarded.
    const asset = /^\/assets\/[a-zA-Z0-9_/-]+\.(?:js|css|png|jpg|jpeg|svg|webp|ico|woff2?)$/.test(url.pathname) && !url.pathname.includes('..');
    if (publicPaths.has(url.pathname) || asset) return env.ASSETS.fetch(request);
    return new Response(request.method === 'HEAD' ? null : missingPage, {
      status: 404,
      headers: { 'Content-Type':'text/html; charset=utf-8', 'X-Robots-Tag':'noindex', 'Cache-Control':'no-store', 'X-Content-Type-Options':'nosniff' }
    });
  }
};
